test("acceptance: backup + restore + restart recovery keeps the project readable and exportable", async (t) => {
 const dir = await mkdtemp(join(tmpdir(), "renovision-acc-rec-"));
 t.after(() => rm(dir, {recursive: true, force: true}));
 const dataDir = join(dir, "data");
 const op = tokenFor();
 const first = await boot(t, dataDir);
 let r = await call(first.base, "POST", "/api/renovision/projects", {token: op, body: {projectId: "acc-1", propertyId: "property-1", roomId: "room-1"}});
 assert.equal(r.status, 201);
 await new Promise((res) => first.server.close(res));
 const backupDir = join(dir, "backup-out");
 const created = await createBackup({sourceDir: dataDir, destDir: backupDir});
 assert.ok(created.fileCount >= 1);
 assert.deepEqual((await verifyBackup({backupDir})).errors, []);
 const restoredRoot = join(dir, "restored");
 await restoreBackup({backupDir, destDir: restoredRoot});
 const second = await boot(t, restoredRoot);
 r = await call(second.base, "GET", P, {token: op});
 assert.equal(r.status, 200);
 assert.equal(r.body.project.projectId, "acc-1");
 r = await call(second.base, "GET", P + "/export", {token: op});
 assert.equal(r.status, 200);
 assert.equal(verifyExportPackage(r.body.export).valid, true);
});
