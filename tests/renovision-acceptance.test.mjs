const {publicKey, privateKey} = generateKeyPairSync("rsa", {modulusLength: 2048});
const jwks = {keys: [{...publicKey.export({format: "jwk"}), kid: "key-1", alg: "RS256", use: "sig"}]};
const ISSUER = "https://issuer.example.com", AUDIENCE = "renovision-api";
const nowSec = Math.floor(Date.now() / 1000);
const b64 = (o) => Buffer.from(JSON.stringify(o)).toString("base64url");
function sign(claims) { const input = b64({alg: "RS256", kid: "key-1", typ: "JWT"}) + "." + b64(claims); const s = createSign("RSA-SHA256"); s.update(input); s.end(); return input + "." + s.sign(privateKey).toString("base64url"); }
const tokenFor = (extra = {}) => sign({sub: "operator-1", iss: ISSUER, aud: AUDIENCE, iat: nowSec - 30, exp: nowSec + 3600, jti: "j-" + Math.random(), tenant_id: "tenant-a", roles: ["operator"], property_ids: ["property-1"], ...extra});
async function boot(t, root) {
 const registry = new Map();
 const authenticator = createTokenAuthenticator({jwksUrl: "https://issuer.example.com/jwks", fetchImpl: async () => ({ok: true, json: async () => jwks}), audience: AUDIENCE, issuer: ISSUER, onActor: (a) => registry.set(a.id, a)});
 const authorize = async ({actorId, tenantId, propertyId, roomId}) => { const a = registry.get(actorId); return Boolean(a) && authorizeAction(a, {action: "project:read", tenantId, propertyId, roomId}).allowed; };
 const server = createRenovisionServer({authenticate: authenticator.authenticate, resolveApproval: createMemoryApprovalRegistry(), evidenceStorage: createDurableEvidenceStorage({rootDir: join(root, "evidence"), authorize}), eventStore: createDurableSpatialEventStore({rootDir: join(root, "events"), authorize: async (s) => authorize({actorId: s?.actor?.id, tenantId: s?.tenantId, propertyId: s?.propertyId, roomId: s?.roomId})}), projectStore: createFileProjectStore({rootDir: join(root, "projects")}), identityMode: "token"});
 await new Promise((r) => server.listen(0, "127.0.0.1", r));
 t.after(() => { try { server.close(); } catch { /* already closed */ } });
 return {server, base: "http://127.0.0.1:" + server.address().port};
}
const call = async (base, method, path, {token, body} = {}) => { const res = await fetch(base + path, {method, headers: {"content-type": "application/json", ...(token ? {authorization: "Bearer " + token} : {})}, body: body ? JSON.stringify(body) : undefined}); return {status: res.status, body: await res.json().catch(() => ({}))}; };
